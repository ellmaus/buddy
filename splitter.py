def _normalize(text: str) -> str:
    return text.lower().replace("ё", "е")


def steps_for(title: str) -> list[str]:
    t = _normalize(title)
    for keys, steps in RULES:
        if any(k in t for k in keys):
            return list(steps)
    return [s.format(task=title) for s in GENERIC]


def tiny_step() -> str:
    return random.choice(TINY)
