"""Все тексты бота в одном месте.

Тон: коротко, тепло, без «должен», без упрёков и счётчиков пропусков.
Формулировки не привязаны к полу пользователя.
"""
import random

WELCOME = (
    "Привет! Я рядом, чтобы помочь начать. Без давления и оценок.\n\n"
    "Напиши одним предложением, что хочется сдвинуть с места, "
    "или нажми «Запусти меня». Я предложу один маленький шаг и посижу рядом, пока идёт таймер."
)

ASK_TASK = "Что хочется сдвинуть? Напиши одним предложением, можно неидеально."

RESTART = (
    "Новый день с чистого листа. Всё, что не получилось, больше не висит над тобой.\n\n"
    "Давай выберем одно дело. Только одно. Что это будет?"
)

STOPPED = "Окей, всё остановил. Когда захочешь, просто напиши, что делаем."
NOTHING_TO_STOP = "Сейчас ничего не запущено. Всё спокойно."

STALE = "Это уже неактуально. Просто напиши новое дело."

LATER = "Окей, без проблем. Когда будет момент, просто напиши. Я никуда не денусь."

MORE = "Отлично, продолжаем ещё 10 минут. Я рядом."

_STARTED = [
    "Поехали! Я рядом.",
    "Начали. Делаем только этот шаг.",
    "Таймер пошёл. Я здесь.",
]

_PRAISE = [
    "Это уже сдвиг. Ты начал(а), а это самое трудное.",
    "Хорошо. Шаг сделан, и этого достаточно.",
    "Супер. Начать было сложнее всего, и ты справился(лась).",
]

_CHECKIN = [
    "Прошло {m} мин. Как идёт?",
    "Я на связи. Прошло {m} мин, как дела?",
    "{m} мин позади. Что у нас?",
]


def propose(step: str, minutes: int) -> str:
    return f"{step}\n\nТолько это и {minutes} мин. Остальное потом."


def started(step: str, minutes: int) -> str:
    return f"{random.choice(_STARTED)}\n\n{step}\n\nНапишу через {minutes} мин."


def checkin(minutes: int) -> str:
    return random.choice(_CHECKIN).format(m=minutes)


def step_done() -> str:
    return f"{random.choice(_PRAISE)}\n\nИдём дальше или на сегодня хватит? Оба варианта хорошие."


def tiny_done() -> str:
    return (
        f"{random.choice(_PRAISE)}\n\n"
        "Хочешь попробовать шаг побольше или остановимся? Оба варианта хорошие."
    )


def all_done() -> str:
    return "Всё сделано. Можно выдохнуть. Это правда здорово."


def enough() -> str:
    return "Отлично, на сегодня достаточно. Ты сделал(а) больше, чем было в начале."


def stuck_then(step: str, minutes: int) -> str:
    return (
        "Бывает, и это нормально. Давай совсем маленький шаг.\n\n"
        f"{step}\n\nТолько это и {minutes} мин."
    )
